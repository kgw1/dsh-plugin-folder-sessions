#!/usr/bin/env node
/**
 * 构建浏览器半：把 `src/client/index.js`（ESM 源码）包进 DSH 的
 * `window.__ModuleLoader__.load({ id, factory })` 手写 bundle 形态。
 *
 * bundle 的 `id` 必须等于 package.json 的 `name`（DSH 的浏览器模块表按包名键控，
 * 不一致会让宿主抛 "loaded without registering"）。这里从 package.json 读取，
 * 避免改名时两处不同步。
 *
 * 用法：node scripts/build-client.mjs
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { createHash } from 'node:crypto'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = join(ROOT, 'src', 'client', 'index.js')
const MANIFEST = join(ROOT, 'package.json')
const OUTPUT = join(ROOT, 'client.js')

/**
 * 读插件包名（= 浏览器模块 id）。
 * @returns {string}
 */
export function readPluginId() {
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'))
  if (typeof manifest.name !== 'string' || manifest.name === '') {
    throw new Error('build-client: package.json has no name')
  }
  return manifest.name
}

/**
 * 去掉源码里的 `export ` 前缀（只处理行首的 function/const/class 声明）。
 * @param {string} source
 * @returns {string}
 */
export function stripExports(source) {
  return source.replace(/^export (function |const |class |let |var )/gm, '$1')
}

/**
 * 生成 bundle 文本。
 * @param {string} source
 * @param {string} pluginId - 浏览器模块表键（package.json name）。
 * @returns {string}
 */
export function buildBundle(source, pluginId) {
  if (typeof pluginId !== 'string' || pluginId === '') throw new Error('build-client: plugin id is required')
  const body = stripExports(source)
  return [
    '/* Generated by scripts/build-client.mjs — do not edit directly.',
    ' * Source: src/client/index.js (run `node scripts/build-client.mjs` after editing).',
    ' * DSH hand-written client-plugin bundle: window.__ModuleLoader__.load({ id, factory }).',
    ` * Bundle id must equal package.json name: ${pluginId}`,
    ' */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(pluginId)},`,
    '  factory: (require) => {',
    '    "use strict";',
    '    const React = require("react");',
    body,
    '    return createPlugin({ React });',
    '  },',
    '});',
    '',
  ].join('\n')
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const pluginId = readPluginId()
  const source = readFileSync(SOURCE, 'utf8')
  const bundle = buildBundle(source, pluginId)
  const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 12)
  const banner = `/* rev: ${hash} */\n`
  writeFileSync(OUTPUT, banner + bundle, 'utf8')
  const lines = bundle.split('\n').length
  console.log(`build-client: wrote ${OUTPUT} (id ${pluginId}, ${lines} lines, rev ${hash})`)
}
